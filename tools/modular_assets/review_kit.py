"""Write docs/modular/REVIEW.md: the reviewer's guide to approving modular assets, in the order worth doing them.

Reads the manifests, the approval ledger, `review_waves.json` and `asset_inventory.json`. For every pack and gear group
it gives the sheets to open, what the inventory already flags, where approval stands and the exact command. The output
has no dates or hashes of its own, so it only changes when one of those inputs does and CI can check it is current:

    python3 -I tools/modular_assets/review_kit.py && git diff --exit-code docs/modular/REVIEW.md
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import approvals  # noqa: E402
import fit as fitmod  # noqa: E402
import scml  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "modular"
WAVES = OUT / "review_waves.json"
INVENTORY = OUT / "asset_inventory.json"
SHEETS = OUT / "verification"
RACE_NAMES = {"valkyrie": "Valkyrie", "forest_ranger": "Elven", "seer": "Seer", "blood_alchemist": "Vampyri",
              "dark_oracle": "Scarred Ones", "necromancer": "Lost Souls", "skeleton_crusader": "Skeletal Undead",
              "skeleton_warrior": "Skeletal Undead", "golem": "Golem"}
CMD = 'python3 -I tools/modular_assets/approvals.py'
WHO = '--reviewer "Your Name"'

# What a reviewer checks on a pack. Each question is answerable from the two sheets; the wording follows the limits
# docs/modular/README.md records for the separation, the masks and the fits.
PACK_QUESTIONS = [
    ("Layers sheet, columns 1 and 4", "Is *recomposite* the same picture as *original*, in the idle row and the attack row? "
     "No missing piece, no pale halo along an edge, no part sitting a pixel off."),
    ("Layers sheet, column 2", "Is *anatomy only* a whole figure: a closed outline, no holes, skin wherever armor was cut away? "
     "It is a flat procedural fill, not painted, and that is expected. A hole or a stray armor fragment is not."),
    ("Layers sheet, column 3", "Does *armor only* hold all of the armor and none of the body? "
     "The dark window where the face was is expected; skin anywhere else is not."),
    ("Layers sheet, column 5", "In the *recolor test*, did every painted surface take its test colour and keep its shading? "
     "A surface left in its original colour is a mask that missed it."),
    ("Layers sheet, column 5", "Did the linework stay dark? No coloured outlines, and no colour crossing an outline into the material next to it."),
    ("Layers sheet, column 5", "Do the left and right of the same thing match: both cheeks, both arms, both boots?"),
    ("Layers sheet, column 5", "Where hair is painted into a helmet or hood it follows the headgear's colour. Is that acceptable on this pack?"),
    ("Fit sheet", "For every profile marked *ok*: is the figure undistorted, with no stretched head, no gap at a joint and nothing cut off? "
     "Profiles marked *UNSUPPORTED* are not offered to players; ignore them."),
    ("This guide", "Have you looked at each thing in the *Check first* column for this pack, and do you accept it?"),
]


def sheets_for(prefix: str, suffixes) -> list:
    return [f"{prefix}{s}.png" for s in suffixes if (SHEETS / f"{prefix}{s}.png").exists()]


def links(names: list) -> str:
    return " · ".join(f"[{n.rsplit('.', 1)[0].split('_')[-1]}](verification/{n})" for n in names) or "none"


def main() -> None:
    waves = json.loads(WAVES.read_text())["waves"]
    inventory = json.loads(INVENTORY.read_text())
    status = approvals.status()
    races = json.loads(approvals.RACES.read_text())
    gear = json.loads(approvals.GEAR.read_text())

    part_flags = defaultdict(list)
    for a in inventory["parts"]:
        for flag in a["flags"]:
            part_flags[a["pack"]].append(f"{a['part']} {a['kind']}: {flag}")
    gear_flags = defaultdict(list)
    for a in inventory["gear"]:
        for flag in a["flags"]:
            gear_flags[a["group"]].append(f"{a['name']}: {flag}")
    race_of = {f"{race}_v{v}": race for race, v in scml.PACKS}
    render_layers = defaultdict(list)
    for p in races["parts"]:
        if p["kind"] != "face":
            render_layers[p["pack"]].append(p)

    def pack_state(pack: str) -> str:
        s = status["packs"][pack]
        if s["rendersModular"]:
            return "**approved** (modular)"
        return f"{s['approved']}/{s['layers']} layers" if s["approved"] else "not reviewed"

    t = status["totals"]
    L = ["# Reviewing modular assets", "",
         "_Generated by `tools/modular_assets/review_kit.py`; do not edit by hand. Regenerate after approving anything._", "",
         "Every modular asset is a `candidate` until a person looks at it and says so. This guide puts that work in the order "
         "worth doing it, and gives the sheets to open and the command to run for each step. You can stop after any wave: "
         "the app is correct at every point along the way.", "",
         "## Where review stands", "",
         f"- **{t['packsRenderingModular']} of {t['packs']}** art packs approved (those render through the modular path).",
         f"- **{t['approved']} of {t['assets']}** assets approved in all; {t['records']} ledger records, {t['revocations']} revocations."]
    if status["stale"]:
        L.append(f"- **{len(status['stale'])} stale approvals**: the asset changed after it was approved, so the approval no longer counts. "
                 "Look again and approve again, or revoke:")
        L += [f"  - {line}" for line in status["stale"]]
    L += ["",
          "## What approving changes, and what it does not", "",
          "- A pack switches to the modular renderer when **every** layer of it is approved, and its body colours unlock in the Forge. "
          "One unapproved layer keeps the whole pack on the legacy renderer.",
          "- Unapproved packs look exactly as they do today. The legacy renderer draws the original art, with the skin, hair and "
          "armor-dye swatches working through the same masks. Nothing goes blank and no hero changes shape.",
          "- An approval is pinned to the files you looked at. If an asset is regenerated later its approval goes stale and the "
          "pack drops back to legacy until someone looks again. `approvals.py status` lists stale approvals.",
          "- Approving is reversible: `" + CMD + " revoke pack:<name> " + WHO + ' --note "why"`.',
          "- Only a person can approve. Nothing in the repository or its CI records an approval for you.", "",
          "## What to look for on a pack", "",
          "Each pack has a **layers** sheet (two rows, idle and attack; five columns: original, anatomy only, armor only, "
          "recomposite, recolor test) and a **fit** sheet (the pack drawn at each body profile). Answer each question; approve "
          "only if every answer is yes.", "",
          "| # | Where | Question |", "|---|---|---|"]
    L += [f"| {n} | {where} | {q} |" for n, (where, q) in enumerate(PACK_QUESTIONS, 1)]
    L += ["",
          "If an answer is no, do not approve. Note which pack, which column and what you saw; the pack simply stays on the "
          "legacy renderer until the asset is fixed.", ""]

    for wave in waves:
        L += [f"## Wave {wave['id']}: {wave['title']}", "", wave["why"], ""]
        if wave["kind"] == "packs":
            L += ["| Pack | Race | Native profile | Sheets | Check first | State | Approve |", "|---|---|---|---|---|---|---|"]
            for pack in wave["packs"]:
                race = race_of[pack]
                flags = "<br>".join(part_flags[pack]) or "nothing flagged"
                L.append(f"| `{pack}` | {RACE_NAMES[race]} | {fitmod.RACE_DEFAULT_PROFILE[race]} | "
                         f"{links(sheets_for(pack, ('_layers', '_fit', '_recolor')))} | {flags} | {pack_state(pack)} | "
                         f"`{CMD} approve pack:{pack} {WHO}` |")
            L.append("")
        elif wave["kind"] == "fits":
            L += ["| Pack | Fit to approve | Sheet | State | Approve (after the pack itself) |", "|---|---|---|---|---|"]
            for race, v in scml.PACKS:
                pack = f"{race}_v{v}"
                s = status["packs"][pack]
                for profile in [p for p in fitmod.PROFILES if p in s["adaptedProfiles"]]:
                    state = "**approved**" if profile in s["approvedProfiles"] else (
                        "not reviewed" if s["rendersModular"] else "waiting for the pack")
                    L.append(f"| `{pack}` | {profile} | {links(sheets_for(pack, ('_fit',)))} | {state} | "
                             f"`{CMD} approve pack:{pack} {WHO} --profile {profile}` |")
            L += ["", "On the fit sheet look only at the named profile: question 8 above.", ""]
        else:
            L += ["Look for: every painted surface recolors, linework and the dark edge band do not, the grip sits in the fist "
                  "in the held views, and nothing is clipped at Titan size.", "",
                  "| Group | Items | Sheets | Check first | State | Approve |", "|---|---|---|---|---|---|"]
            overview = {"signature": "gear_assets_signature", "store": "gear_assets_store", "staff": "gear_assets_staves",
                        "shield": "gear_assets_shields"}
            for group in wave["groups"]:
                items = [i for i in gear["items"] if i["group"] == group]
                family = group.rstrip("0123456789")
                own = sheets_for(f"gear_{group}", ("", "_1", "_2", "_3"))
                names = own + sheets_for(overview[family], ("",))
                label = items[0]["name"].rsplit(" ", 1)[0] if family in ("staff", "shield") else group
                s = status["gear"][group]
                state = "**approved**" if s["approved"] == s["items"] else (f"{s['approved']}/{s['items']}" if s["approved"] else "not reviewed")
                flags = "<br>".join(gear_flags[group]) or "nothing flagged"
                L.append(f"| `{group}` {label if label != group else ''} | {len(items)} | "
                         + " · ".join(f"[{n[:-4]}](verification/{n})" for n in names)
                         + f" | {flags} | {state} | `{CMD} approve group:{group} {WHO}` |")
            L.append("")

    L += ["## After approving", "",
          "```sh",
          f"{CMD} status                        # what is approved, what is stale",
          "python3 -I tools/modular_assets/validate.py                  # must exit 0",
          "python3 -I tools/modular_assets/checklist.py                 # refresh CHECKLIST.md",
          "python3 -I tools/modular_assets/review_kit.py                # refresh this guide",
          "```", "",
          "Commit `docs/modular/approvals.json`, the two manifests under `ios/PurgeQuest/Art/Modular/`, `CHECKLIST.md`, "
          "`asset_status.json` and this file together. Then check the approved packs on an iPhone: the Dashboard strip, "
          "an Armory tile, a dive, and the Forge's body colours.", ""]
    (OUT / "REVIEW.md").write_text("\n".join(L))
    print("wrote REVIEW.md", len(L), "lines")


if __name__ == "__main__":
    main()
