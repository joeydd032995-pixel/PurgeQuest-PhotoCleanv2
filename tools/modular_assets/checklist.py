"""Generate docs/modular/CHECKLIST.md and asset_status.json from the manifests + approvals ledger.

Every row separates what automation established ("mapped" / "candidate") from what a human approved
("verified"). Run after build_assets.py / held_gear.py / approvals.py apply.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import fit as fitmod
import validate

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "modular"
RACE_NAMES = {"valkyrie": "Valkyrie", "forest_ranger": "Elven", "seer": "Seer", "blood_alchemist": "Vampyri", "dark_oracle": "Scarred Ones",
              "necromancer": "Lost Souls", "skeleton_crusader": "Skeletal Undead (v1-3, crusader pack)",
              "skeleton_warrior": "Skeletal Undead (v4-6, warrior pack)", "golem": "Golem"}
MARK = {"verified": "VERIFIED", "candidate": "candidate", "mapped": "mapped", "unsupported": "unsupported", "unstarted": "unstarted"}


def status_of(entries) -> str:
    states = {e["verification"]["status"] for e in entries}
    for s in ("mapped", "unstarted", "unsupported", "candidate"):
        if s in states:
            return s
    return "verified"


def main() -> None:
    races = json.loads(validate.RACES.read_text())
    gear = json.loads(validate.GEAR.read_text())
    report = json.loads((OUT / "race_build_report.json").read_text())
    ledger = json.loads(validate.LEDGER.read_text())["approvals"]
    by_pack = defaultdict(list)
    for p in races["parts"]:
        by_pack[p["pack"]].append(p)

    lines = ["# Modular assets — completion checklist", "",
             "_Generated by `tools/modular_assets/checklist.py`; do not edit by hand._", "",
             "**Mapped is not verified.** `mapped` = resources exist and structural checks ran. `candidate` = every automated check passed "
             "(reassembly, masks, fit bounds, clipping) and QA sheets exist. `verified` = a human approval is recorded in "
             "`docs/modular/approvals.json`. Modular rendering activates only for recipes whose every part is `verified`; "
             "everything else keeps using the legacy renderer.", ""]
    counts = defaultdict(int)
    for e in races["parts"] + gear["items"]:
        counts[e["verification"]["status"]] += 1
    lines += ["## Summary", "", "| status | assets |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(counts.items())]
    lines += ["", f"Approvals recorded: **{len(ledger)}**. Race part layers: {len(races['parts'])} across {len(races['packs'])} art packs. "
                  f"Held/store gear: {len(gear['items'])} items.", ""]

    # ---- races
    lines += ["## Races: separated anatomy, armor, masks, fit", "",
              "Columns — **Layers**: anatomy/armor/headgear layers produced · **Masks**: material regions recolorable · "
              "**Reassembly**: mean pixel error original vs anatomy+armor, Idle/attack (limit 5e-4) · **Fit**: body profiles with an in-range fit "
              "(others are unsupported and hidden) · **Sheets**: `docs/modular/verification/` · **Approval**: human gate.", "",
              "| Pack | Layers (A/Arm/Hd) | Masks | Reassembly Idle / attack | Supported profiles | Status | Approval |", "|---|---|---|---|---|---|---|"]
    approved_ids = {r["assetId"] for r in ledger if not r.get("profile")}
    for race, v in __import__("scml").PACKS:
        pid = f"{race}_v{v}"
        parts = by_pack[pid]
        kinds = defaultdict(int)
        for p in parts:
            kinds[p["kind"]] += 1
        regions = sorted({r for p in parts for r in p["materialRegions"]})
        checks = report[pid]["checks"]["reassembly"]
        idle = checks.get("Idle", {}).get("mean")
        atk = next((x["mean"] for k, x in checks.items() if k != "Idle"), None)
        ref = fitmod.RACE_DEFAULT_PROFILE[race]
        torso = next(p for p in parts if p["part"] == "body" and p["kind"] == "anatomy")
        profiles = []
        for prof in fitmod.PROFILES:
            ok = all(prof in (p["nativeProfiles"] + p["adaptedProfiles"]) for p in parts if p["kind"] != "face")
            if ok:
                profiles.append(f"{prof}{'*' if prof == ref else ''}")
        approved = sum(p["id"] in approved_ids for p in parts)
        lines.append(f"| `{pid}` {RACE_NAMES[race].split(' (')[0]} | {kinds['anatomy']}/{kinds['armor']}/{kinds['headgear']} | {', '.join(regions)} | "
                     f"{idle:.1e} / {atk:.1e} | {', '.join(profiles) or 'reference only'} | {MARK[status_of(parts)]} | {approved}/{len(parts)} |")
    lines += ["", "`*` = the race's native profile. A profile is listed only when **every** part of the pack fits inside its safe scale range; "
                  "otherwise that (race, profile) combination is `unsupported` and is not offered. Every supported adapted fit still needs its own "
                  "approval (`approvals.py approve <pack> --profile <name>`).", ""]

    # ---- gear
    def table(title, items, extra):
        out = [f"### {title}", "", "| ID | Name | " + extra[0] + " | Status |", "|---|---|" + "---|" * len(extra[0].split("|")) + "---|"]
        for i in items:
            out.append(f"| `{i['id']}` | {i['name']} | {extra[1](i)} | {MARK[i['verification']['status']]} |")
        return out + [""]

    def growth(i):
        g = i["verification"]["automated"].get("canvasGrowth", {})
        t = g.get("titan") or g.get("1x") or [1, 1]
        return f"{max(t):.2f}x"

    sig = [i for i in gear["items"] if i["group"] == "signature"]
    lines += ["## Held gear", "",
              "Grip, hold, scale, rotation, layering and profile overrides are recorded per item in `modular_gear_manifest.json`. "
              "Weapons/shields keep the grip on the pack's hold at any scale; Titan Blade is `2.0x` about the grip "
              "(canvas growth below is the worst case across packs). Profile overrides: none required — hand anchors do not change with body profile.", ""]
    lines += table("Signature weapons (8, including the Elven Recurve bow)", sig,
                   ("Grip px | Masks | Titan canvas growth | Packs", lambda i: f"{i['gripPx']} | {', '.join(sorted(i['maskResources']))} | {growth(i)} | {len(i['supportedPacks'])}"))
    bow = next(i for i in sig if i["kind"] == "bow")
    sa = bow["verification"]["automated"]["stringAlignment"]["forest_ranger_v1"]
    lines += ["**Elven Recurve (checked separately from swords):** supported only on `forest_ranger_v1`/`v2` (v3 is a sword pack with no Shooting animation). "
              "The bow art has no string; the renderer draws one from the recorded tip anchors "
              f"{bow['stringAnchors']} through the arrow nock while the arrow is drawn (nock to chord {sa['meanNockToChordPx']}px mean over {sa['frames']} frames).", ""]

    for kind, label, group_prefix in (("staff", "Staves (40)", "staff"), ("shield", "Shields (40)", "shield")):
        lines += [f"### {label}", "", "| Set | " + " | ".join(["I", "II", "III", "IV", "V"]) + " | Masks (set I) | Max Titan growth |", "|---|---|---|---|---|---|---|---|"]
        for s in range(1, 9):
            items = [i for i in gear["items"] if i["group"] == f"{group_prefix}{s}"]
            items.sort(key=lambda i: i["id"])
            lines.append(f"| {items[0]['name'].rsplit(' ', 1)[0]} | " + " | ".join(MARK[i["verification"]["status"]] for i in items) +
                         f" | {', '.join(sorted(items[0]['maskResources']))} | {max(float(growth(i)[:-1]) for i in items):.2f}x |")
        lines.append("")

    store = [i for i in gear["items"] if i["group"] == "store"]
    lines += ["## Remaining store gear (IDs, prices, ownership, unlocks unchanged)", "",
              "The three headpieces (Starlit Cap, Shadow Hood, Dragoncrest Helm) were drawn and then **removed on request**; their catalog entries are unchanged and still render in the vector avatar.", ""]
    lines += table("9 weapons, 2 named shields", store,
                   ("Kind | Masks | Packs", lambda i: f"{i['kind']} | {', '.join(sorted(i['maskResources']))} | {len(i['supportedPacks'])}"))

    lines += ["## Open gates (cannot be closed from an automated session)", "",
              "- [ ] **Visual approval** of every `candidate` above — review `docs/modular/verification/*.png`, then record with `tools/modular_assets/approvals.py`.",
              "- [ ] **Per-profile fit approval** for each supported adapted profile (see `*_fit.png`).",
              "- [ ] Run the Xcode unit tests and `PurgeQuestUITests/ForgeUITests` on an iOS simulator (CI runs both; see `.github/workflows/ios.yml`).",
              "- [ ] **Physical iPhone**: small previews (Dashboard strip, Armory tiles), combat rendering, relaunch persistence of equipment and colours, memory under repeated Forge use.",
              "- [ ] Hair masks: hair is painted into headgear on several packs and is not separately masked; the legacy hair-hue slider still applies on the legacy path.",
              "- [ ] Golem and bone races have no separable armor art for some parts (their body *is* the material); those parts ship as anatomy only.", ""]
    (OUT / "CHECKLIST.md").write_text("\n".join(lines))
    status = {e["id"]: {"status": e["verification"]["status"], "kind": e.get("kind")} for e in races["parts"] + gear["items"]}
    (OUT / "asset_status.json").write_text(json.dumps(status, indent=1, sort_keys=True) + "\n")
    print("wrote CHECKLIST.md", len(lines), "lines")


if __name__ == "__main__":
    main()
